    public List<GruppaNasosov> getGruppy() {
        return gruppy;
    }

    public List<MarkaNasosa> getMarkiNasosov() {
        return marki;
    }

    public List<MarkaNasosa> getMarkiPoGruppe(String gruppaSlug) {
        return marki.stream().filter(m -> m.getGruppaSlug().equals(gruppaSlug)).toList();
    }

    public MarkaNasosa getMarku(String slug) {
        return marki.stream().filter(m -> m.getSlug().equals(slug)).findFirst().orElse(null);
    }

    public List<ModelNasosa> getModeliPoMarke(String markaSlug) {
        return modeli.stream()
                .filter(m -> m.getMarkaSlug().equals(markaSlug))
                .sorted((a, b) -> {
                    int poPodache = Double.compare(a.getPodacha(), b.getPodacha());
                    return poPodache != 0 ? poPodache : Double.compare(a.getNapor(), b.getNapor());
                })
                .toList();
    }

    public ModelNasosa getModel(String markaSlug, String modelSlug) {
        return modeli.stream()
                .filter(m -> m.getMarkaSlug().equals(markaSlug) && m.getSlug().equals(modelSlug))
                .findFirst().orElse(null);
    }

    public List<ModelNasosa> getVseModeli() {
        return modeli;
    }

    public int vsegoModeley() {
        return modeli.size();
    }

