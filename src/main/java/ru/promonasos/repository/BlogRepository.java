    public List<StatyaBloga> getStati() {
        return stati.stream().sorted(Comparator.comparing(StatyaBloga::getData).reversed()).toList();
    }

    public List<StatyaBloga> getStatiPoRubrike(String rubrika) {
        if (rubrika == null || rubrika.isEmpty()) {
            return getStati();
        }
        return stati.stream()
                .filter(s -> s.getRubrika().equals(rubrika))
                .sorted(Comparator.comparing(StatyaBloga::getData).reversed())
                .toList();
    }

    public StatyaBloga getStatyu(String slug) {
        return stati.stream().filter(s -> s.getSlug().equals(slug)).findFirst().orElse(null);
    }

    /** Статьи, связанные с маркой насоса, — блок перелинковки на странице марки. */
    public List<StatyaBloga> getStatiPoMarke(String markaSlug) {
        return stati.stream()
                .filter(s -> s.getSvyazannyeMarki().contains(markaSlug))
                .sorted(Comparator.comparing(StatyaBloga::getData).reversed())
                .toList();
    }

    public List<String> getRubriki() {
        return stati.stream().map(StatyaBloga::getRubrika).distinct().sorted().toList();
    }
